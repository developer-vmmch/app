/**
 * Calculates today's 23:59:59 local boundary timestamp.
 * Requirement 5: "The daily expiry boundary is 23:59:59 local time, followed by the midnight reset.
 * Do NOT interpret this requirement as a rolling 24-hour expiry."
 */
export function getLocalMidnightExpiry(): string {
  const now = new Date();
  const midnight = new Date(now.getFullYear(), now.getMonth(), now.getDate(), 23, 59, 59, 999);
  return midnight.toISOString();
}

